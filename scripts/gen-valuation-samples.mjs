/**
 * Барилгын өртгийн хандлагын баганыг ОРОЛТООС тооцоолно (Excel-ийн томьёотой ижил):
 *   бүрэн орлуулах = нэгж өртөг × талбай × итгэлцүүрүүдийн үржвэр
 *   элэгдлийн дүн  = бүрэн орлуулах × элэгдлийн хувь / 100
 *   нөхөн орлуулах = бүрэн орлуулах − элэгдлийн дүн
 * Ингэснээр жишээ өгөгдөл өөртөө нийцтэй болж, шалгалт (validation) хуурамч
 * анхааруулга өгөхгүй.
 */
function buildingCosts({ unit, area, coeffs, deprPct }) {
  const product = coeffs.reduce((p, c) => p * c, 1);
  const full = round2(unit * area * product);
  const depr = round2((full * deprPct) / 100);
  const net = round2(full - depr);
  return [unit, area, ...coeffs, full, deprPct, depr, net];
}

