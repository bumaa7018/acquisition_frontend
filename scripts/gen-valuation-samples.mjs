function buildSheet(ws, d) {
  const merges = [];
  let r = 0;
  const put = (values, opts = {}) => {
    r++;
    const row = ws.getRow(r);
    values.forEach((v, i) => {
      if (v !== null && v !== undefined && v !== "") row.getCell(i + 1).value = v;
    });
    if (opts.bold) row.font = { bold: true };
    if (opts.merge) merges.push(`${opts.merge}${r}:${opts.mergeEnd ?? "G"}${r}`);
    (opts.merges ?? []).forEach(([a, b]) => merges.push(`${a}${r}:${b}${r}`));
    return r;
  };
  const note = (text) => put([`${NOTE_PREFIX} ${text ?? ""}`.trim()], { merge: "A" });
  const sectionTitle = (title, tableLabel) =>
    put([title, null, null, null, null, null, tableLabel ?? null], {
      bold: true,
      merges: tableLabel ? [["A", "F"]] : [["A", "G"]],
    });

  // Толгой
  put([DOC_TITLE], { bold: true, merge: "A" });
  put([d.intro], { merge: "A" });

  // ── 3.1 Үнэлж буй хөрөнгүүдийн танилцуулга (Хүснэгт 1) ──
  sectionTitle("3.1 Үнэлж буй хөрөнгүүдийн танилцуулга", "Хүснэгт 1");
  put(
    ["№", "Үнэлж буй хөрөнгийн нэр", "Хэмжих нэгж", "Хүчин чадал", "Үнэлж буй хөрөнгийн тодорхойлолт"],
    { bold: true, merges: [["E", "G"]] },
  );
  d.properties.forEach(([name, unit, qty, desc], i) => {
    put([i + 1, name, unit, qty, desc], { merges: [["E", "G"]] });
  });

  // ── 3.2 Газрын эрх зүйн байдал (Хүснэгт-2) ──
  sectionTitle("3.2 Газрын эрх зүйн байдлын мэдээлэл", "Хүснэгт-2");
  put(["№", "Үзүүлэлт", null, null, "Тодорхойлолт"], {
    bold: true,
    merges: [
      ["B", "D"],
      ["E", "G"],
    ],
  });
  d.landLegal.forEach(([k, v], i) => {
    put([i + 1, k, null, null, v], {
      merges: [
        ["B", "D"],
        ["E", "G"],
      ],
    });
  });

  // ── 3.3 Газрын үнэлгээ (Хүснэгт-3) ──
  const landTotal = round2(d.landArea * d.landUnitPrice);
  sectionTitle("3.3. Газрын үнэлгээ", "Хүснэгт-3");
  put(["№", "Үзүүлэлт", null, null, null, "Хэмжих нэгж", "Дүн"], {
    bold: true,
    merges: [["B", "E"]],
  });
  put([1, "Чөлөөлөлтөнд өртсөн газрын хэмжээ", null, null, null, "м2", d.landArea], {
    merges: [["B", "E"]],
  });
  put([2, "Газрын 1 м2 талбайн суурь үнэ", null, null, null, "Төгрөг", d.landUnitPrice], {
    merges: [["B", "E"]],
  });
  put([3, "Газрын үнэлгээ", null, null, null, "Төгрөг", landTotal], { merges: [["B", "E"]] });
  note(d.landNote);

  // ── 3.4 Барилгын тодорхойлолт (Хүснэгт-4) ──
  // Эх загварт ТАЙЛБАР мөр нь ГАРЧГИЙН ДАРАА, толгойн ӨМНӨ байдаг — тэр байрлалыг хадгална.
  sectionTitle("3.4. Барилгын тодорхойлолт", "Хүснэгт-4");
  note(d.buildingSpecNote);
  const bCols = ["C", "E", "G"]; // барилга тус бүрийн багана (тогтмол, 3 хүртэл)
  const specHeader = ["№", "Барилгын үзүүлэлт"];
  d.buildings.forEach((b, i) => {
    specHeader[colIndex(bCols[i]) - 1] = b.name;
  });
  put(specHeader, {
    bold: true,
    merges: d.buildings.length > 1 ? [["C", "D"], ["E", "F"]] : [["C", "D"]],
  });
  SPEC_ROWS.forEach((label, ri) => {
    const row = [ri + 1, label];
    d.buildings.forEach((b, bi) => {
      row[colIndex(bCols[bi]) - 1] = b.specs[ri];
    });
    put(row, { merges: d.buildings.length > 1 ? [["C", "D"], ["E", "F"]] : [["C", "D"]] });
  });

  // ── 3.5 Өртгийн хандлагаарх тооцоолол (Хүснэгт-5) ──
  sectionTitle("3.5. Барилга байгууламжийн өртгийн хандлагаарх тооцоолол", "Хүснэгт-5");
  const costHeader = ["№", "Үзүүлэлт", null, "Хэмжих нэгж"];
  d.buildings.forEach((b, i) => {
    costHeader[4 + i] = b.name; // E, F, G
  });
  put(costHeader, { bold: true, merges: [["B", "C"]] });
  let coeffStart = 0;
  let coeffEnd = 0;
  COST_ROWS.forEach(([group, label, unit], ri) => {
    const row = [ri + 1];
    if (group) {
      row[1] = group; // B — merge хийгдэх бүлгийн толгой
      row[2] = label; // C
    } else {
      row[1] = label;
      row[2] = null;
    }
    row[3] = unit;
    d.buildings.forEach((b, bi) => {
      row[4 + bi] = b.cost[ri];
    });
    const written = put(row, group ? {} : { merges: [["B", "C"]] });
    if (group) {
      if (!coeffStart) coeffStart = written;
      coeffEnd = written;
    }
  });
  if (coeffStart && coeffEnd > coeffStart) merges.push(`B${coeffStart}:B${coeffEnd}`);
  note(d.buildingCostNote);

  // ── 3.6 Бусад эд хөрөнгө (Хүснэгт-6) ──
  sectionTitle("3.6. Бусад эд хөрөнгийн зардлын тооцоолол", "Хүснэгт-6");
  put(["№", "Хөрөнгийн нэрс", null, "Хэмжих нэгж", "Хүчин чадал", "Нэгж үнэ", "Нийт үнэ"], {
    bold: true,
    merges: [["B", "C"]],
  });
  let otherTotal = 0;
  d.otherAssets.forEach(([name, unit, qty, price], i) => {
    const total = round2(qty * price);
    otherTotal += total;
    put([i + 1, name, null, unit, qty, price, total], { merges: [["B", "C"]] });
  });
  put([null, "Нийт", null, null, null, null, round2(otherTotal)], {
    bold: true,
    merges: [["B", "C"]],
  });
  note(d.otherAssetsNote);

  // ── 3.7 / 3.8 / 3.9 зардлын хүснэгтүүд ──
  const costTable = (title, label, rows, noteText) => {
    sectionTitle(title, label);
    put(["№", "Зардлын нэр", null, "Хэмжих нэгж", "Тоо хэмжээ", "Нэгжийн үнэ", "Нийт үнэ"], {
      bold: true,
      merges: [["B", "C"]],
    });
    let sum = 0;
    rows.forEach(([name, unit, qty, price], i) => {
      const total = round2(qty * price);
      sum += total;
      put([i + 1, name, null, unit, qty, price, total], { merges: [["B", "C"]] });
    });
    note(noteText);
    return round2(sum);
  };
  const tempTotal = costTable("3.7. Түр суурьшуулах зардал", "Хүснэгт-7", d.temporary, d.temporaryNote);
  const clearTotal = costTable("3.8 Газар чөлөөлөх зардал", "Хүснэгт-8", d.clearance, d.clearanceNote);
  const lostTotal = costTable("3.9 Орлогын алдагдсан боломж", "Хүснэгт-9", d.lostIncome, d.lostIncomeNote);

  // ── 4.1 Хураангуй нэгтгэл ──
  sectionTitle("4.1. Хөрөнгийн үнэлгээний тайлангийн хураангуй нэгтгэл", "Хүснэгт-10");
  put(["№", "Хөрөнгийн үнэлгээний зүйлс", null, null, null, "Хүчин чадал", "Хөрөнгийн үнэлгээ"], {
    bold: true,
    merges: [["B", "E"]],
  });
  const summaryRows = [["Газрын үнэлгээ", `${d.landArea} м.кв`, landTotal]];
  d.buildings.forEach((b, i) => {
    summaryRows.push([`Хувийн сууц-${i + 1}`, `${b.cost[1]} м.кв`, b.cost[9]]);
  });
  summaryRows.push(["Бусад эд хөрөнгө", `${d.otherAssets.length} төрөл`, round2(otherTotal)]);
  summaryRows.push(["Түр суурьшуулах зардал", "3 сар", tempTotal]);
  summaryRows.push(["Газар чөлөөлөх зардал", `${d.clearance.length} төрөл`, clearTotal]);
  if (lostTotal > 0) summaryRows.push(["Орлогын алдагдсан боломж", "3 сар", lostTotal]);
  summaryRows.forEach(([label, capacity, value], i) => {
    put([i + 1, label, null, null, null, capacity, value], { merges: [["B", "E"]] });
  });
  const grand = round2(summaryRows.reduce((s, x) => s + x[2], 0));
  put([null, "Нийт", null, null, null, null, grand], { bold: true, merges: [["B", "E"]] });

  // ── 4.2 дүгнэлт ──
  sectionTitle("4.2. Хөрөнгийн үнэлгээний тайлангийн дүгнэлт", null);
  put(
    [
      `Иргэн ${d.owner}-н өмчлөл, эзэмшлийн хөрөнгийн нөхөн олговрын дүнг бүхэлчилж ${grand.toLocaleString("en-US")} төгрөгөөр тогтоов.`,
    ],
    { merge: "A" },
  );

  // ── ТАВ. Нийцэлтийн мэдэгдэл ──
  put(["ТАВ. НИЙЦЭЛТИЙН МЭДЭГДЭЛ, ХАВСРАЛТ"], { bold: true, merge: "A" });
  sectionTitle("5.1 Үнэлгээний баталгаа, хязгаарлах нөхцөл", null);
  note(d.certificationNote);

  merges.forEach((m) => {
    try {
      ws.mergeCells(m);
    } catch {
      // давхацсан merge — алгасна (загварын бүтцэд нөлөөлөхгүй)
    }
  });

  ws.columns = [
    { width: 6 },
    { width: 42 },
    { width: 16 },
    { width: 16 },
    { width: 16 },
    { width: 16 },
    { width: 18 },
  ];
  ws.eachRow((row) => {
    row.alignment = { vertical: "middle", wrapText: true };
  });
}

function colIndex(letter) {
  return letter.charCodeAt(0) - 64; // A=1
}
function round2(n) {
  return Math.round(n * 100) / 100;
}

async function write(d) {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Sheet1");
  buildSheet(ws, d);
  const out = path.join(OUT_DIR, d.file);
  await wb.xlsx.writeFile(out);
  console.log("бичив:", path.relative(path.join(__dirname, ".."), out));
}

